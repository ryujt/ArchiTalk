import {test,expect} from './fixtures.mjs';
import {writeFile} from 'node:fs/promises';

test('document generation resumes a persisted prefix and only publishes the complete reviewed package',async({server,productPage},testInfo)=>{
  const {page,errors,violations}=productPage;
  await page.goto(server.origin,{waitUntil:'domcontentloaded'});
  await page.locator('#project-intro').fill('합성 문서별 생성·실패 복구와 로컬 알림 설계입니다.');
  await page.locator('#start-form button[type=submit]').click();
  await expect(page.locator('.chat-turn')).toHaveCount(2);
  await page.getByRole('button',{name:'도구 설정',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.locator('#timeout-seconds').fill('1800');
  await page.locator('#settings-form button[type=submit]').click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await server.configureDocumentStages({failKind:'decisions'});
  await page.locator('[data-action=generate]').click();
  await expect(page.getByRole('heading',{name:'작업을 완료하지 못했어요',exact:true})).toBeVisible();
  await expect(page.locator('.generation-progress')).toContainText('문서 3/10 완료');
  await expect(page.getByRole('button',{name:'남은 문서 이어 만들기',exact:true})).toBeEnabled();
  await expect(page.getByRole('button',{name:'처음부터 새로 생성',exact:true})).toBeEnabled();
  await expect(page.locator('[data-action=save-preview]')).toHaveCount(0);
  await expect(page.locator('[data-action=approve]')).toHaveCount(0);
  const failed=await server.workspace(),sessionId=failed.sessions[0].id;
  const first=failed.sessions[0].design_generations.at(-1);
  expect(first.completed.map(part=>part.document.kind)).toEqual(['drivers','quality_scenarios','alternatives']);
  expect(failed.sessions[0].drafts).toHaveLength(0);
  expect(failed.runs).toHaveLength(2);
  await page.screenshot({path:testInfo.outputPath('01-three-documents-preserved.png'),fullPage:true,animations:'disabled'});
  await page.reload({waitUntil:'domcontentloaded'});
  await expect(page.getByRole('heading',{name:'남겨 둔 설계에서 이어가세요',exact:true})).toBeVisible();
  await expect(page.locator('.generation-progress')).toContainText('문서 3/10 완료');
  expect((await server.workspace()).runs).toEqual(failed.runs);
  await server.configureDocumentStages({holdKind:'decisions'});
  await page.getByRole('button',{name:'남은 문서 이어 만들기',exact:true}).click();
  await expect(page.locator('.pending-turn')).toContainText('문서 3/10 완료');
  await expect(page.locator('.pending-turn [data-current-document]')).toHaveText('현재 문서: 아키텍처 결정 기록');
  await expect(page.locator('.pending-turn')).toContainText('요청당 시간 제한: 1800초 (30분)');
  const resumed=await server.workspace(),resumingRun=resumed.active_run.id;
  expect(resumed.sessions[0].design_generations.at(-1).id).toBe(first.id);
  expect(resumed.sessions[0].design_generations.at(-1).completed).toEqual(first.completed);
  expect(resumed.sessions[0].drafts).toHaveLength(0);
  await page.screenshot({path:testInfo.outputPath('02-resuming-next-document.png'),fullPage:true,animations:'disabled'});
  await server.configureDocumentStages();
  await expect.poll(async()=>{const w=await server.workspace();return w.active_run===null&&w.sessions[0].drafts[0]?.reviewed;}).toBe(true);
  const completed=await server.workspace(),generation=completed.sessions[0].design_generations.at(-1);
  expect(completed.sessions[0].drafts).toHaveLength(1);
  expect(generation.completed).toHaveLength(10);
  expect(generation.completed.slice(0,3)).toEqual(first.completed);
  expect(generation.completed.slice(3).every(part=>part.source_run_id===resumingRun)).toBe(true);
  expect(generation.draft_id).toBe(completed.sessions[0].drafts[0].id);
  expect(completed.runs.map(run=>[run.kind,run.status])).toEqual([['conversation','completed'],['design','failed'],['design','completed'],['critic','completed']]);
  expect(completed.sessions[0].messages.filter(message=>message.role==='user')).toHaveLength(1);
  await expect(page.locator('#document-kind-picker option')).toHaveCount(10);
  await expect(page.locator('.markdown')).toHaveAttribute('data-render-state','ready');
  const finishedDraft=completed.sessions[0].drafts[0];
  await page.locator('#document-kind-picker').selectOption('state');
  await server.configureDocumentStages({failKind:'decisions'});
  await page.locator('[data-action=generate]').click();
  await expect(page.getByRole('heading',{name:'작업을 완료하지 못했어요',exact:true})).toBeVisible();
  const secondFailed=await server.workspace();
  expect(secondFailed.sessions[0].design_generations).toHaveLength(2);
  expect(secondFailed.sessions[0].design_generations[0]).toEqual(generation);
  expect(secondFailed.sessions[0].drafts).toEqual([finishedDraft]);
  await server.configureDocumentStages({holdKind:'drivers'});
  await page.getByRole('button',{name:'처음부터 새로 생성',exact:true}).click();
  await expect(page.locator('.pending-turn')).toContainText('문서 0/10 완료');
  await expect(page.locator('#document-kind-picker')).toHaveValue('state');
  const restarted=await server.workspace();
  expect(restarted.sessions[0].design_generations).toHaveLength(3);
  expect(restarted.sessions[0].design_generations.at(-1).id).not.toBe(secondFailed.sessions[0].design_generations.at(-1).id);
  expect(restarted.sessions[0].drafts).toEqual([finishedDraft]);
  await page.screenshot({path:testInfo.outputPath('03-fresh-generation-preserves-draft.png'),fullPage:true,animations:'disabled'});
  await server.configureDocumentStages();
  await expect.poll(async()=>{const w=await server.workspace();return w.active_run===null&&w.sessions[0].drafts.length===2&&w.sessions[0].drafts[1].reviewed;}).toBe(true);
  await expect(page.locator('.markdown')).toHaveAttribute('data-render-state','ready');
  await page.locator('[data-action=save-preview]').click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.locator('.plan-file')).toHaveCount(10);
  await page.locator('[data-action=export-apply]').click();
  await expect(page.getByRole('heading',{name:'설계 문서를 저장했어요',exact:true})).toBeVisible();
  const saved=await server.workspace(),output=saved.exports.at(-1).result.paths;
  expect(output).toHaveLength(10);
  for(const path of output)expect(await server.savedFile(path)).toContain('style: smartmd');
  expect(saved.sessions[0].messages.filter(message=>message.role==='user')).toHaveLength(1);
  expect(saved.sessions[0].id).toBe(sessionId);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:testInfo.outputPath('04-complete-package-published.png'),fullPage:true,animations:'disabled'});
  await writeFile(testInfo.outputPath('stage-boundary.json'),JSON.stringify({preservedPrefix:3,resumedDocuments:7,totalDocuments:10,generations:3,drafts:2,exported:10,userMessages:1},null,2));
  expect(errors).toEqual([]);expect(violations).toEqual([]);
});
